package javaoperators;

public class Shiftoperator {

	public static void main(String[] args) {
		int a = 54;
		int b = 2;
		
		System.out.println(a<<b);
		System.out.println(a>>b);
		System.out.println(a>>>b);
		
		int a1 = 93;
		int b1 = 3;
		
		System.out.println(a1<<b1);
		System.out.println(a1>>b1);
		System.out.println(a1>>>b1);
		

	}

}
